DECLARE @Metadata TABLE
(
      EntryOrdinal          int            NOT NULL
    , EntryName             nvarchar(1024) NOT NULL
    , IsDirectory           bit            NOT NULL
    , CompressedBytes       bigint         NOT NULL
    , UncompressedBytes     bigint         NOT NULL
    , CompressionMethod     int            NOT NULL
    , Crc32                 int            NOT NULL
    , IsEncrypted           bit            NOT NULL
    , IsExtractionSupported bit            NOT NULL
    , DuplicateCount        int            NOT NULL
    , IsPathSafe            bit            NOT NULL
    , PathStatus            varchar(32)    NOT NULL
    , LastModifiedAt        datetime2(0)   NULL
);

INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipEmpty;

IF EXISTS (SELECT 1 FROM @Metadata)
    THROW 51420, N'Ein leeres gültiges ZIP muss ein leeres Resultset liefern.', 1;

INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipStored;

IF NOT EXISTS
   (
       SELECT 1 FROM @Metadata
       WHERE EntryOrdinal = 1
         AND EntryName = N'plain.txt'
         AND IsDirectory = 0
         AND CompressedBytes = 5
         AND UncompressedBytes = 5
         AND CompressionMethod = 0
         AND Crc32 = -1052482506
         AND IsEncrypted = 0
         AND IsExtractionSupported = 1
         AND DuplicateCount = 1
         AND IsPathSafe = 1
         AND PathStatus = 'safe'
         AND LastModifiedAt IS NOT NULL
   )
    THROW 51421, N'Der Stored-Metadatenvertrag ist falsch.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipDuplicate;

IF (SELECT COUNT(*) FROM @Metadata WHERE EntryName = N'dup.txt' AND DuplicateCount = 2) <> 2
    THROW 51422, N'Duplicate Names werden nicht korrekt markiert.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipEncrypted;

IF NOT EXISTS
   (
       SELECT 1 FROM @Metadata
       WHERE IsEncrypted = 1
         AND IsExtractionSupported = 0
   )
    THROW 51423, N'Verschlüsselte Entries werden nicht korrekt markiert.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipUnsupported;

IF NOT EXISTS
   (
       SELECT 1 FROM @Metadata
       WHERE CompressionMethod = 12
         AND IsExtractionSupported = 0
   )
    THROW 51424, N'Unbekannte Methoden müssen als nicht extrahierbar gelistet werden.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipPaths;

IF NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'folder/' AND IsDirectory = 1 AND PathStatus = 'safe')
   OR NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'../escape.txt' AND IsPathSafe = 0 AND PathStatus = 'parent-traversal')
   OR NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'C:/drive.txt' AND IsPathSafe = 0 AND PathStatus = 'drive-qualified')
   OR NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'folder//odd.txt' AND IsPathSafe = 0 AND PathStatus = 'noncanonical')
    THROW 51425, N'Directory- oder Pfadsicherheitsmetadaten sind falsch.', 1;

DECLARE @EncodedName nvarchar(50) = N'Gr' + NCHAR(252) + NCHAR(223) + N'e.txt';

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipUtf8;
IF NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = @EncodedName)
    THROW 51431, N'Der UTF-8-Metadatenname ist falsch.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipCp437;
IF NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = @EncodedName)
    THROW 51432, N'Der CP437-Metadatenname ist falsch.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipDescriptor;
IF NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'descriptor.txt')
    THROW 51433, N'Der Data-Descriptor-Metadatenpfad ist falsch.', 1;

DELETE FROM @Metadata;
INSERT INTO @Metadata
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary @ZipArchive = @ZipBadTime;
IF NOT EXISTS (SELECT 1 FROM @Metadata WHERE EntryName = N'plain.txt' AND LastModifiedAt IS NULL)
    THROW 51434, N'Eine ungültige DOS-Zeit muss NULL liefern.', 1;

CREATE TABLE #ZipMetadataResult (IgnoredDummy int NULL);
EXEC toolbelt_archive.USP_ListZipEntriesFromBinary
      @ZipArchive = @ZipStored
    , @ResultTable = N'#ZipMetadataResult';

IF NOT EXISTS (SELECT 1 FROM #ZipMetadataResult WHERE EntryName = N'plain.txt')
    THROW 51426, N'Der Metadaten-ResultTable-Pfad hat keine Zeile geschrieben.', 1;

EXEC toolbelt_archive.USP_ListZipEntriesFromBinary
      @ZipArchive = @ZipDuplicate
    , @ResultTable = N'#ZipMetadataResult'
    , @KeepData = 1;

IF (SELECT COUNT(*) FROM #ZipMetadataResult) <> 3
    THROW 51427, N'Der Metadaten-ResultTable-Append-Pfad ist falsch.', 1;

